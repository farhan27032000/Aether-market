-- Schema for the `listings` table used by app/page.tsx.
-- Run in the Supabase SQL editor.

create table if not exists public.listings (
  id bigint generated by default as identity primary key,
  title text not null,
  location text,
  country text,               -- ISO 3166-1 alpha-2 code, e.g. 'US', 'AE'
  market_category text,       -- 'real-estate' | 'vehicles' | 'electronics' | 'industrial' | 'services'
  subcategory text,
  condition text,
  price text,
  description text,
  image_url text,
  seller_name text,
  seller_phone text,
  latitude double precision,
  longitude double precision,
  created_at timestamptz not null default now()
);

create index if not exists listings_country_idx on public.listings (country);
create index if not exists listings_created_at_idx on public.listings (created_at desc);

alter table public.listings enable row level security;

-- Anyone can browse listings.
create policy "Public read listings" on public.listings
  for select using (true);

-- Publish Direct inserts with the anon key. Tighten this (e.g. to authenticated users) once auth is added.
create policy "Public insert listings" on public.listings
  for insert with check (true);

-- Optional: public bucket for original photos uploaded via Publish Direct.
insert into storage.buckets (id, name, public)
values ('listing-images', 'listing-images', true)
on conflict (id) do nothing;

create policy "Public upload listing images" on storage.objects
  for insert with check (bucket_id = 'listing-images');
